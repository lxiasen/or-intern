async def stochastic_builder_handler(args: dict[str, Any]) -> tuple[str, bool]:
    """Handler for stochastic_builder tool."""
    description = args.get("description", "")
    n_scenarios = args.get("n_scenarios", 100)
    solver = args.get("solver", "highs")

    if not description:
        return "Error: No problem description provided", True

    try:
        code = generate_stochastic_model(description, n_scenarios, solver)

        rundir = get_run_dir()
        model_file = rundir / "model_stochastic.py"
        model_file.write_text(code, encoding="utf-8")

        uncertain_params = parse_uncertainty_description(description)

        result = (
            f"## Stochastic Programming Model Generated\n\n"
            f"**Type**: Two-stage stochastic programming\n"
            f"**Scenarios**: {n_scenarios}\n"
            f"**Uncertain Parameters**: {', '.join(uncertain_params.keys()) or 'N/A'}\n"
            f"**Solver**: {solver}\n"
            f"**Model file**: {model_file}\n\n"
            f"### Next Steps\n\n"
            f"1. Review the generated model code\n"
            f"2. Customize recourse constraints as needed\n"
            f"3. Run with `solve_job` to solve the stochastic program\n"
        )

        return result, False

    except Exception as e:
        logger.error(f"stochastic_builder failed: {e}")
        return f"Error building stochastic model: {e}", True
