def _detect_uncertainty_set_type(description: str) -> str:
    """Detect the type of uncertainty set from description."""
    desc_lower = description.lower()

    if "ellipsoid" in desc_lower or "budget" in desc_lower or "gamma" in desc_lower:
        return "ellipsoidal"
    if "box" in desc_lower or "interval" in desc_lower or "[" in desc_lower:
        return "box"
    return "box"


def _extract_bounds(description: str) -> dict[str, tuple[float, float]]:
    """Extract parameter bounds from description."""
    bounds = {}

    interval_pattern = re.compile(
        r"(\w+)\s*(?:in|∈)\s*\[([0-9.]+),\s*([0-9.]+)\]"
    )
    for match in interval_pattern.finditer(description):
        name = match.group(1)
        low = float(match.group(2))
        high = float(match.group(3))
        bounds[name] = (low, high)

    return bounds


def generate_robust_model(
    description: str,
    solver: str = "highs",
    gamma: float = 1.0,
) -> str:
    """Generate a robust optimization model.

    Args:
        description: Problem description with uncertainty information
        solver: Solver to use
        gamma: Budget of uncertainty for ellipsoidal set

    Returns:
        Pyomo model code as string
    """
    set_type = _detect_uncertainty_set_type(description)
    bounds = _extract_bounds(description)

    uncertain_params = parse_uncertainty_description(description)

    var_match = re.findall(r"\b([a-zA-Z_]\w*)\b", description)
    main_vars = []
    for v in var_match:
        if v.lower() not in ("minimize", "maximize", "subject", "to", "where",
                              "robust", "uncertain", "demand", "cost",
                              "the", "and", "or", "in"):
            if v not in main_vars and len(v) <= 5:
                main_vars.append(v)

    if not main_vars:
        main_vars = ["x"]

    lines_vars = []
    for v in main_vars[:5]:
        lines_vars.append(f"model.{v} = Var(domain=NonNegativeReals)")

    lines_con = []
    for v in main_vars[:5]:
        if v in bounds:
            low, high = bounds[v]
            if set_type == "box":
                lines_con.append(f"# Robust constraint for {v}: worst-case at bound")
                lines_con.append(f"# model.robust_{v} = Constraint(expr=model.{v} >= ...)")
            else:
                lines_con.append(f"# Ellipsoidal robust constraint for {v}")

    if not lines_con:
        lines_con.append("# Add robust constraints here")
        lines_con.append("# model.c1 = Constraint(expr=...)")

    obj_expr = " + ".join(f"model.{v}" for v in main_vars[:5])
    if not obj_expr:
        obj_expr = "0"

    result_lines = []
    for v in main_vars[:5]:
        result_lines.append(f"print('  {v} =', value(model.{v}))")

    if set_type == "box":
        lower_str = str(bounds.get(main_vars[0], (0, 100))[0]) if main_vars else "0"
        upper_str = str(bounds.get(main_vars[0], (0, 100))[1]) if main_vars else "100"

        code = BOX_REFORMULATION_TEMPLATE.format(
            lower=lower_str,
            upper=upper_str,
            variables="\n".join(lines_vars),
            robust_constraints="\n".join(lines_con),
            objective=obj_expr,
            sense="minimize",
            solver=solver,
            result_output="\n".join(result_lines),
        )
    else:
        code = ELLIPSOIDAL_TEMPLATE.format(
            gamma=gamma,
            variables="\n".join(lines_vars),
            robust_constraints="\n".join(lines_con),
            objective=obj_expr,
            sense="minimize",
            solver=solver,
            result_output="\n".join(result_lines),
        )

    return code


