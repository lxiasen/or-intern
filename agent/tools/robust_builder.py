async def robust_builder_handler(args: dict[str, Any]) -> tuple[str, bool]:
    """Handler for robust_builder tool."""
    description = args.get("description", "")
    uncertainty_set = args.get("uncertainty_set", "box")
    gamma = args.get("gamma", 1.0)
    solver = args.get("solver", "highs")

    if not description:
        return "Error: No problem description provided", True

    try:
        code = generate_robust_model(description, solver, gamma)

        rundir = get_run_dir()
        model_file = rundir / "model_robust.py"
        model_file.write_text(code, encoding="utf-8")

        bounds = _extract_bounds(description)

        result = (
            f"## Robust Optimization Model Generated\n\n"
            f"**Type**: Robust optimization\n"
            f"**Uncertainty Set**: {uncertainty_set}\n"
            f"**Uncertain Parameters**: {', '.join(bounds.keys()) or 'N/A'}\n"
        )

        if uncertainty_set == "ellipsoidal":
            result += f"**Budget (Gamma)**: {gamma}\n"

        result += (
            f"**Solver**: {solver}\n"
            f"**Model file**: {model_file}\n\n"
            f"### Next Steps\n\n"
            f"1. Review the generated model code\n"
            f"2. Customize robust constraints as needed\n"
            f"3. Run with `solve_job` to solve the robust problem\n"
        )

        return result, False

    except Exception as e:
        logger.error(f"robust_builder failed: {e}")
        return f"Error building robust model: {e}", True
